_ROWS = [row for row in LOGO_ROWS_32 if '#' in row]
_LEFT = min(row.index('#') for row in _ROWS)
_RIGHT = max(row.rindex('#') for row in _ROWS)
# The mark alone, cropped to its lit pixels: 23 wide, 28 tall.
MARK = tuple(row[_LEFT:_RIGHT + 1] for row in _ROWS)
MARK_WIDTH, MARK_HEIGHT = len(MARK[0]), len(MARK)


def mark_pixels(left=0, top=0):
    """The (x, y) of each lit pixel of the mark, with its top-left corner at (left, top)."""
    return [(left + x, top + y) for y, row in enumerate(MARK) for x, ch in enumerate(row) if ch == '#']


def zone_color(i, width):
    """The zone colour of column i of a zone bar `width` wide: five equal bands."""
    return ZONE_COLORS[min(4, i * 5 // width)]
